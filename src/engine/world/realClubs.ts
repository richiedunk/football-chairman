/**
 * Real club names.
 *
 * The game ships with the actual clubs, in their actual divisions, and nothing
 * else real: players, staff, agents, owners and stadiums are all generated.
 * The disclaimer in `src/ui/views/AboutView.vue` states the position, and it is
 * the same one the genre has long used — club names are used descriptively, to
 * say which club a thing happened to, and for no other purpose.
 *
 * Each entry is `name|shortName|city|founded|primary|secondary|nickname`.
 * A compact string beats an object literal at this volume: five hundred clubs
 * of `{ name: ..., shortName: ... }` is thirty pages nobody will ever read,
 * and a column that drifts out of line is obvious here in a way it is not
 * there.
 *
 * Where a division is not filled, world generation makes up the rest, so the
 * pack can be as complete or as partial as it is accurate.
 */

export interface RealClub {
  name: string
  shortName: string
  city: string
  founded: number
  primary: string
  secondary: string
  nickname: string
}

function parse(rows: string[]): RealClub[] {
  return rows.map((row) => {
    const [name, shortName, city, founded, primary, secondary, nickname] = row.split('|')
    return {
      name,
      shortName,
      city,
      founded: Number(founded),
      primary,
      secondary,
      nickname: nickname ?? '',
    }
  })
}

